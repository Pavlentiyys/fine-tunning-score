"""Your solution.

The harness imports this package and calls `apply()` once, in the same process as `soup train`,
before Soup builds the model and the trainer. Patch whatever you need (transformers, peft,
bitsandbytes, Soup itself) so the training run uses your Triton kernels.

The rules in short (the README and the task statement have the full ones):
- your own `@triton.jit` kernels, defined in this folder, run in every measured run and together
  take >= 5% of the training time; the example's kernels (however renamed or rewritten) and
  kernels generated by torch.compile do not count;
- no ready-made kernel libraries (unsloth, liger-kernel, xformers, flash-attn, torchao, ...);
- the task stays the same: model, data, batches and their order, steps, LoRA, optimizer, Soup's
  settings and outputs; no other GPU, no background processes, no tricks with the measurement.
"""

from .dequant import patch_bnb_matmul_4bit
from .warmup import start_background_compile
from .timeline import mark, patch_timeline
from .stream import patch_bnb_offload
from .prepare import patch_embedding_load_to_cpu, patch_kbit_preparation, patch_no_allocator_warmup
from .lora import patch_peft_lora_4bit
from .fused_ce import patch_qwen2_causal_lm, patch_sft_trainer
from .rmsnorm import patch_qwen2_rmsnorm
from .mlp import patch_qwen2_mlp_own
from .rope import patch_qwen2_rope
from .unpad import patch_qwen2_model


def apply():
    patch_timeline()  # [time] lines in train.log: load / train / save split (prints only)
    start_background_compile()  # our kernels compile while Soup loads the model
    patch_bnb_matmul_4bit()  # NF4 weight dequantized once for recompute + backward
    patch_bnb_offload()  # 4-bit weights go to pinned CPU memory as they are quantized
    patch_no_allocator_warmup()  # no model-sized reservation before loading (it was the peak)
    patch_embedding_load_to_cpu()  # the tied embedding / lm_head is loaded to (pinned) CPU memory
    patch_kbit_preparation()  # the tied embedding stays fp16: no fp32 copy, no allocator spike
    patch_qwen2_mlp_own()  # our SwiGLU, backward in place over the saved gate/up
    patch_qwen2_rmsnorm()  # fp32 residual in, fp16 out: the layer's activations become fp16
    patch_qwen2_rope()  # q/k rotation in one kernel, fp16 out, nothing saved
    patch_qwen2_model()  # everything but RoPE+SDPA on real tokens only; tied embedding in fp16
    patch_peft_lora_4bit()  # LoRA: dropout mask regenerated from a seed, no clone, one addmm
    patch_qwen2_causal_lm()  # head + loss + entropy/argmax in chunks, no full logits
    patch_sft_trainer()  # TRL metrics and Soup's rewind losses from the fused step
    mark("apply done")
